def hashed(t, kind, full, only, intro, title, summary):
    unit = 'entries' if kind == 'Maps' else 'elements'
    D = load(t)
    on, off = D['coh-on'], D['coh-off']
    v = {l: [on[l][s] / 1e6 for s in SHOW] for l in full}
    c1 = grouped(t, 'footprint', full, v, {l: [mb(on[l][s]) for s in SHOW] for l in full},
                 f'{kind} of Integers: memory held once filled, JDK vs Eclipse Collections',
                 f'Lower is better. At 1,000,000 {unit}: ' + ', '.join(f'{STYLE[l][0].split(" (")[0]} {mb(on[l][10**6])}' for l in full) +
                 '. Compact headers on.',
                 'retained size (MB), compact headers on', groups=[f'{s:,} {unit}' for s in SHOW])
    v = {l: [on[l][s] / 1e6 for s in SHOW] for l in only}
    c2 = grouped(t, 'structure-only', only, v, {l: [mb(on[l][s]) for s in SHOW] for l in only},
                 f'{kind}: memory for the {kind.lower()[:-1]} itself, without the Integers it holds',
                 'Lower is better. The Integers are subtracted (16 B each), leaving tables and entry objects. The JDK '
                 f'{"HashSet wraps a HashMap, which" if kind == "Sets" else "HashMap"} makes one entry object per element; '
                 'Eclipse Collections stores elements directly in its table.',
                 'retained size (MB) without the Integers, compact headers on', groups=[f'{s:,} {unit}' for s in SHOW])
    labels = full + [l for l in only if l not in full]
    c3 = coh_bars(t, 'coh', labels, {l: off[l][10**6] for l in labels}, {l: on[l][10**6] for l in labels},
                  f'{kind} with 1,000,000 {unit}: compact object headers off vs on',
                  'Lower is better. Compact headers shrink every object header from 12 to 8 bytes. Only the JDK '
                  f'{"HashSet" if kind == "Sets" else "HashMap"} gets smaller, because only it has one object per entry; '
                  'the Integers (16 B either way) and the arrays do not change.')
    a = header(t, title, intro)
    a += ['== Summary', ''] + summary(on, off) + ['']
    a += ['== Memory held once filled', ''] + embed(c1, f'Retained size of each {kind.lower()[:-1]}, compact headers on')
    a += ['== The structure alone', ''] + embed(c2, f'Retained size without the Integers, compact headers on')
    a += ['== Compact headers off vs on', ''] + embed(c3, f'Retained size at 1,000,000 {unit}, compact headers off vs on')
    a += ['[cols="3,1,1,1",options="header"]', '|===', f'|Collection (1,000,000 {unit}) |Headers off (B) |Headers on (B) |Saved']
    for l in labels:
        o, n = off[l][10**6], on[l][10**6]
        a.append(f'|{STYLE[l][0]} |{o:,} |{n:,} |{o - n:,} B ({(o - n) / o * 100:.0f}%)')
    a += ['|===', '', '== Every measurement', ''] + table(D, labels) + footer(t)
    write(t, a)


