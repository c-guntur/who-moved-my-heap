def load(test):
    """-> {cfg: {label: {size: bytes}}} for the size tests, {cfg: [(jdk, jb, ec, eb)]} for the pipeline test."""
    out = {}
    for cfg in CFGS:
        text = open(f'{SRC}/{test}Results-{cfg}.md', encoding='utf-8').read()
        if test == 'StreamVsLazyIterableMemory':
            rows = []
            for line in text.splitlines():
                p = [c.strip() for c in line.split('|')]
                if line.startswith('`') and len(p) >= 4:
                    rows.append((p[0].strip('`'), int(p[1]), p[2].strip('`'), int(p[3])))
            out[cfg] = rows
        else:
            d = {}
            for m in re.finditer(r'^(.+?) size: (\d+) Memory \(bytes\): (\d+)$', text, re.M):
                d.setdefault(m.group(1), {})[int(m.group(2))] = int(m.group(3))
            out[cfg] = d
    return out


def mb(b):
    return f'{b / 1e6:,.1f} MB'


def mmd(path, title, ylabel, cats, vals):
    cats = [' ' * 14 + c for c in cats]  # NBSP pad: Mermaid under-measures label width
    lines = ['---', 'config:', '  xyChart:', '    width: 1400', f'    height: {max(500, 30 * len(cats) + 140)}',
             '    chartOrientation: horizontal', '    xAxis:', '      labelFontSize: 13', '  themeVariables:', '    xyChart:',
             '      plotColorPalette: "#0072B2"', '---',
             '%% Generated by movers.py. The PNG next to this file is the same data with colours and a legend.',
             'xychart-beta', f'  title "{title}"',
             '  x-axis [' + ', '.join(f'"{c}"' for c in cats) + ']',
             f'  y-axis "{ylabel}" 0 --> {max(vals) * 1.1:.4g}',
             '  bar [' + ', '.join(f'{v:.4g}' for v in vals) + ']']
    open(path, 'w').write('\n'.join(lines) + '\n')
    if MMDC:
        subprocess.run([MMDC, '-i', path, '-o', '/tmp/_movers_check.svg', '-q'] +
                       (['-p', os.environ['MMDC_PP']] if os.environ.get('MMDC_PP') else []), check=True)


def finish(fig, ax, title, subtitle, name, ncol=1, foot=None):
    ax.spines[['top', 'right']].set_visible(False)
    fig.suptitle(title, fontsize=14, fontweight='bold', x=0.01, ha='left')
    ax.set_title(textwrap.fill(subtitle, 130), fontsize=10.5, loc='left', color='#333333')
    ax.legend(loc='upper left', bbox_to_anchor=(0, -0.1), ncol=ncol, fontsize=9.5, frameon=False)
    if foot:
        fig.text(0.01, 0.005, textwrap.fill(foot, 150), fontsize=8.5, color='#555555', ha='left', va='bottom')
    fig.tight_layout(rect=(0, 0.02, 1, 0.96))
    fig.savefig(f'{CH}/{name}.png', facecolor='white', bbox_inches='tight')
    plt.close(fig)


def grouped(test, key, labels, values, text, title, subtitle, ylabel, foot=None, groups=None):
    """Vertical grouped bars: one group per size (or per `groups`), one bar per label."""
    groups = groups or [f'{s:,} elements' for s in SHOW]
    n = len(labels)
    fig, ax = plt.subplots(figsize=(12, 6.2), dpi=150)
    w = 0.8 / n
    vmax = max(v for l in labels for v in values[l])
    for i, l in enumerate(labels):
        legend, colour, hatch = STYLE.get(l, (l, JDK, ''))
        xs = [g + (i - (n - 1) / 2) * w for g in range(len(groups))]
        bars = ax.bar(xs, values[l], w * 0.92, color=colour, hatch=hatch, edgecolor='white', linewidth=0.8, label=legend)
        for b, t in zip(bars, text[l]):
            ax.annotate(t, (b.get_x() + b.get_width() / 2, b.get_height()), xytext=(0, 3), textcoords='offset points',
                        ha='center', va='bottom', fontsize=8.5, rotation=90 if n > 3 else 0)
    ax.set_xticks(range(len(groups)))
    ax.set_xticklabels(groups, fontsize=11)
    ax.set_ylabel(ylabel, fontsize=11)
    ax.set_ylim(0, vmax * (1.45 if n > 3 else 1.25))
    ax.grid(axis='y', alpha=0.3)
    name = f'{RUN_TS}-{test}-{key}'
    finish(fig, ax, title, subtitle, name, foot=foot)
    cats, vals = [], []
    for g, gl in enumerate(groups):
        for l in labels:
            cats.append(f'{gl}: {STYLE.get(l, (l,))[0]} = {text[l][g]}')
            vals.append(values[l][g])
    mmd(f'{MMD_DIR}/{name}.mmd', title, ylabel, cats, vals)
    return name


def coh_bars(test, key, labels, off, on, title, subtitle, unit='MB'):
    """Horizontal pairs: compact headers off (grey) vs on (dark blue) for each label, with the saving."""
    fig, ax = plt.subplots(figsize=(12, 1.4 + 0.7 * len(labels)), dpi=150)
    ys = list(range(len(labels)))[::-1]
    h = 0.38
    scale = 1e6 if unit == 'MB' else 1
    fmt = (lambda v: f'{v / 1e6:,.1f} MB') if unit == 'MB' else (lambda v: f'{v:,.0f} B')
    b1 = ax.barh([y + h / 2 for y in ys], [off[l] / scale for l in labels], h, color=OFF, edgecolor='white', label='compact headers off')
    b2 = ax.barh([y - h / 2 for y in ys], [on[l] / scale for l in labels], h, color=ON, edgecolor='white',
                 label='compact headers on (-XX:+UseCompactObjectHeaders)')
    for bars, src in ((b1, off), (b2, on)):
        for bar, l in zip(bars, labels):
            ax.text(bar.get_width() * 1.01, bar.get_y() + bar.get_height() / 2, fmt(src[l]), va='center', fontsize=9)
    top = max(off[l] for l in labels) / scale
    for y, l in zip(ys, labels):
        d = off[l] - on[l]
        txt = f'saves {fmt(d)} ({d / off[l] * 100:.0f}%)' if d / off[l] >= 0.005 else 'no change'
        ax.text(top * 1.17, y, txt, va='center', fontsize=9.5, color=ON if txt != 'no change' else '#555555', fontweight='bold')
    ax.set_yticks(ys)
    ax.set_yticklabels([STYLE.get(l, (l,))[0] for l in labels], fontsize=10)
    ax.set_xlim(0, top * 1.55)
    ax.set_xlabel(f'retained size ({unit})', fontsize=11)
    name = f'{RUN_TS}-{test}-{key}'
    finish(fig, ax, title, subtitle, name, ncol=2)
    cats, vals = [], []
    for l in labels:
        for c, src in (('headers off', off), ('headers on', on)):
            cats.append(f'{STYLE.get(l, (l,))[0]}, {c} = {fmt(src[l])}')
            vals.append(src[l] / scale)
    mmd(f'{MMD_DIR}/{name}.mmd', title, f'retained size ({unit})', cats, vals)
    return name


def embed(name, caption):
    return [f'.{caption}', f'image::{IMG_LINK}/{name}.png[{caption}]', f'Mermaid source: link:{MMD_LINK}/{name}.mmd[{name}.mmd]', '']


def table(D, labels, per_elem_minus=0):
    """Every size, both configurations."""
    a = ['[cols="3,1,1,1,1",options="header"]', '|===',
         '|Collection |Elements |Headers off (B) |Headers on (B) |B per element (on)']
    for l in labels:
        for s in SIZES:
            off, on = D['coh-off'][l][s], D['coh-on'][l][s]
            a.append(f'|{STYLE.get(l, (l,))[0]} |{s:,} |{off:,} |{on:,} |{on / s:.1f}')
    return a + ['|===', '']


def header(test, title, intro):
    return [f'= {title} (JOL baselines {RUN_TS})', ':toc:', ':toclevels: 2', '',
            intro + ' Sizes are JOL retained sizes (`GraphLayout.parseInstance(x).totalSize()`): every object reachable '
            'from the collection, measured once it is filled. They show memory *footprint*, not what building the '
            'collection allocated along the way, and not speed. ' + f'Environment: {env(test)}. '
            'JOL sizes depend on the JVM layout (compressed references, object alignment, header size), not the '
            f'machine. The results files `{SRC_REL}/{test}Results-coh-off.md` and '
            f'`{test}Results-coh-on.md` start with the JDK, JOL and Eclipse Collections versions and the full JVM details.', '']


def env(test):
    """Environment and JDK from the HTML comment at the top of the coh-on results file (instructions2.md M3.3)."""
    head = open(f'{SRC}/{test}Results-coh-on.md', encoding='utf-8').read().split('-->')[0]
    lines = [l.strip() for l in head.replace('<!--', '').splitlines() if l.strip()]
    where = next((l.split(':', 1)[1].strip() for l in lines if l.startswith('environment:')), lines[0] if lines else 'not recorded')
    java = next((l for l in lines if 'version "' in l), 'JDK version not recorded')
    return f'{where} ({java})'


def footer(test):
    return ['== Caveats', '',
            '* JOL counts every reachable object once. Values 1 to 127 come from the `Integer` cache and are shared; with '
            '100,000 or more elements that is under 0.13% of the `Integer`s.',
            '* Retained size includes unused capacity (empty array slots), so a grown collection is larger than a presized one.',
            '* Layout explanations marked "derived" are arithmetic from the measured totals and the JVM details, not '
            'separate measurements.', '',
            '== Reproduce', '', '....',
            f'mvn test -Dtest={test}Test -Dsurefire.failIfNoSpecifiedTests=false \\',
            '  -DargLine="-XX:-UseCompactObjectHeaders -Djdk.attach.allowAttachSelf=true -XX:+EnableDynamicAgentLoading"',
            '# then again with -XX:+UseCompactObjectHeaders; save the printed lines as',
            f'# {SRC_REL}/{test}Results-coh-{{off,on}}.md',
            f'python3 assets/tools/movers/movers.py . {RUN_TS}', '....', '']


def write(test, lines):
    path = f'{OUT}/{RUN_TS}-{test}Analysis.adoc'
