"""Self-explanatory charts for one benchmark class.

Each chart is drawn twice from the same numbers:
  <name>.png  matplotlib grouped bars: one group per match position, one coloured bar per
              implementation, a legend that says what each colour is, and the value printed on
              every bar. This is the image the analysis docs embed.
  <name>.mmd  Mermaid xychart-beta source with the same title; every bar's label names the
              implementation, the match position and the value (Mermaid has no legend).
"""
import os, subprocess, textwrap
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

OP = {'AnyMatch': 'anyMatch', 'Count': 'count', 'FindFirst': 'findFirst'}
SOURCE = {'Utility': 'on a JDK ArrayList (EC via Iterate)', 'EagerLazy': 'on an EC ImmutableList (eager and lazy)'}
TEST_LABEL = {1: 'match at element 1', 500: 'match at element 500', 1000: 'match at element 1000'}
# Colour-blind-safe Okabe-Ito colours, one per kind, the same in every chart. No red/green pairs.
# A second method of the same kind keeps the colour and gets a hatch pattern, so colour is never
# the only cue (legend, hatch and the value on every bar also identify each bar).
COLOURS = {'jdk': '#E69F00',    # orange: JDK stream
           'cap': '#56B4E9',    # sky blue: EC eager, capturing
           'lazy': '#CC79A7',   # reddish purple: EC lazy, capturing
           'free': '#0072B2',   # dark blue: EC *With, fat-free
           'bound': '#000000'}  # black: EC *With that Predicates.bind makes capturing
HATCHES = ['', '//', '..', 'xx']


def op_of(cls):
    for k, v in OP.items():
        if cls.startswith(k): return v, SOURCE[cls[len(k):]]


def classify(cls, m):
    """Returns (family, plain description) for a benchmark method."""
    if m.startswith('jdk'): return 'jdk', 'JDK stream (builds a pipeline each call)'
    lazy = m.startswith('ecLazy')
    if 'With' in m:
        if cls.endswith('EagerLazy') and m != 'ecDetectWithOptional':
            return 'bound', 'EC *With, but ImmutableList wraps it in Predicates.bind (not fat-free)'
        return 'free', 'EC *With: fat-free (non-capturing) lambda'
    if lazy: return 'lazy', 'EC lazy (asLazy), capturing lambda'
    return 'cap', 'EC eager, capturing lambda'


def styles(cls, ms):
    used = {}
    out = {}
    for m in ms:
        fam, desc = classify(cls, m)
        i = used.get(fam, 0); used[fam] = i + 1
        out[m] = (COLOURS[fam], HATCHES[i % len(HATCHES)], f'{m}: {desc}')
    return out


def png(path, title, subtitle, ylabel, groups, ms, style, values, labels, footnote=None):
    """groups: x groups (match positions); values[m][g] numbers; labels[m][g] text on the bar."""
    n = len(ms)
    fig, ax = plt.subplots(figsize=(12, 6.2), dpi=150)
    width = 0.8 / n
    vmax = max([v for m in ms for v in values[m]] + [1e-9])
    for i, m in enumerate(ms):
        xs = [g + (i - (n - 1) / 2) * width for g in range(len(groups))]
        colour, hatch, legend = style[m]
        bars = ax.bar(xs, values[m], width * 0.92, color=colour, label=legend, hatch=hatch,
                      edgecolor='white', linewidth=0.8)
        for b, txt in zip(bars, labels[m]):
            ax.annotate(txt, (b.get_x() + b.get_width() / 2, b.get_height()), xytext=(0, 3),
                        textcoords='offset points', ha='center', va='bottom',
                        fontsize=8.5 if n > 4 else 9.5, rotation=90 if n > 4 else 0)
    ax.set_xticks(range(len(groups)))
    ax.set_xticklabels(groups, fontsize=11)
    ax.set_ylabel(ylabel, fontsize=11)
    ax.set_ylim(0, vmax * (1.45 if n > 4 else 1.25))
    ax.spines[['top', 'right']].set_visible(False)
    ax.grid(axis='y', alpha=0.3)
    fig.suptitle(title, fontsize=14, fontweight='bold', x=0.01, ha='left')
    ax.set_title(textwrap.fill(subtitle, 130), fontsize=10.5, loc='left', color='#333333')
    ax.legend(loc='upper left', bbox_to_anchor=(0, -0.09), ncol=1 if n > 3 else 1, fontsize=9.5, frameon=False)
    if footnote:
        fig.text(0.01, 0.005, textwrap.fill(footnote, 150), fontsize=8.5, color='#555555', ha='left', va='bottom')
    fig.tight_layout(rect=(0, 0.02, 1, 0.97))
    fig.savefig(path, facecolor='white', bbox_inches='tight')
    plt.close(fig)


def mmd(path, title, ylabel, groups_short, ms, values, labels, mmdc=None, pp=None):
    cats, vals = [], []
    for g, gs in enumerate(groups_short):
        for m in ms:
            cats.append('\u00a0' * 14 + f'{m} {gs} = ' + labels[m][g].replace(chr(10), ' '))  # NBSP pad: Mermaid under-measures label width
            vals.append(values[m][g])
    vmax = max(vals + [1e-9])
    lines = ['---', 'config:', '  xyChart:', '    width: 1400', f'    height: {max(500, 34 * len(cats) + 120)}',
             '    chartOrientation: horizontal', '    xAxis:', '      labelFontSize: 13', '  themeVariables:', '    xyChart:', '      plotColorPalette: "#0072B2"', '---',
             '%% Generated by gen.py. Each bar label reads: match position, benchmark method = value.',
             '%% The PNG next to this file is the same data as grouped, coloured bars with a legend.',
             'xychart-beta', f'  title "{title}"',
             '  x-axis [' + ', '.join(f'"{c}"' for c in cats) + ']',
             f'  y-axis "{ylabel}" 0 --> {vmax * 1.1:.4g}',
             '  bar [' + ', '.join(f'{v:.4g}' for v in vals) + ']']
    open(path, 'w').write('\n'.join(lines) + '\n')
    if mmdc:  # parse check only; the embedded PNG comes from matplotlib
        subprocess.run([mmdc] + (['-p', pp] if pp else []) + ['-i', path, '-o', '/tmp/_mmd_check.svg', '-q'], check=True)


def rng(xs):
    lo, hi = b(min(xs)), b(max(xs))
    return lo if lo == hi else f'{lo} to {hi}'


def b(x):
    return '0 B' if x < 0.5 else f'{x:,.0f} B'


def build(cls, ms, D, tests, charts_dir, run_ts, mmdc=None, pp=None, mmd_dir=None):
    """Writes all charts for one class; returns [(key, caption, png, mmd)] in doc order.
    PNGs go to charts_dir; Mermaid sources go to mmd_dir (defaults to charts_dir)."""
    mmd_dir = mmd_dir or charts_dir
    op, src = op_of(cls)
    style = styles(cls, ms)
    jdk = [m for m in ms if m.startswith('jdk')][0]
    ec = [m for m in ms if m != jdk]
    groups = [TEST_LABEL[t] for t in tests]
    short = [f'@{t}' for t in tests]
    on, off, ea = D['coh-on'], D['coh-off'], D['ea-off']
    out = []

    def emit(key, title, subtitle, ylabel, values, labels, caption, footnote=None):
        name = f'{run_ts}-{cls}-{key}'
        png(f'{charts_dir}/{name}.png', title, subtitle, ylabel, groups, ms, style, values, labels, footnote)
        mmd(f'{mmd_dir}/{name}.mmd', title, ylabel, short, ms, values, labels, mmdc, pp)
        out.append((key, caption, name + '.png', name + '.mmd'))

    # 1. speed
    rel = {m: [on[(jdk, t)]['ns'] / on[(m, t)]['ns'] for t in tests] for m in ms}
    lab = {m: [f'{r:.1f}x\n{on[(m, t)]["mcalls"]:,.1f} M/s' if len(ms) <= 4 else f'{r:.1f}x' for r, t in zip(rel[m], tests)] for m in ms}
    best = max(ec, key=lambda m: rel[m][0])
    emit('throughput', f'{op} {src}: how many times faster than the JDK stream',
         f'Higher is better. JDK stream = 1x. At element 1, {best} is {rel[best][0]:.0f}x faster; '
         f'labels also show million calls per second.',
         'times as fast as the JDK stream (JDK = 1)', rel, lab,
         'Speed relative to the JDK stream, compact headers on.')

    # 2. garbage per call
    v = {m: [on[(m, t)]['bytes'] for t in tests] for m in ms}
    emit('bytes-per-call', f'{op} {src}: garbage left behind per call',
         f'Lower is better. The JDK stream leaves {rng(v[jdk])} per call; '
         f'every EC version leaves {b(max(max(v[m]) for m in ec))}. Escape analysis on (normal JVM).',
         'bytes allocated per call', v, {m: [b(x) for x in v[m]] for m in ms},
         'Bytes allocated per call (gc.alloc.rate.norm), compact headers on.')

    # 3. GC per billion calls
    v = {m: [on[(m, t)]['gc_per_b'] for t in tests] for m in ms}
    emit('gc-per-billion', f'{op} {src}: garbage collections per billion calls',
         f'Lower is better. G1 with a 2 GB heap. The JDK stream needs about {max(v[jdk]):,.0f} young '
         f'collections per billion calls; EC needs {max(max(v[m]) for m in ec):,.0f}.',
         'GC runs per 1 billion calls', v, {m: [f'{x:,.0f}' for x in v[m]] for m in ms},
         'Garbage collections per billion calls, compact headers on.')

    # 4. escape analysis off
    v = {m: [ea[(m, t)]['bytes'] for t in tests] for m in ms}
    free = [m for m in ec if classify(cls, m)[0] == 'free']
    cap = [m for m in ec if classify(cls, m)[0] in ('cap', 'lazy')]
    sub = 'Lower is better. With escape analysis off the JIT cannot delete short-lived objects, so this shows what each lambda shape really costs.'
    if free and cap:
        sub += (f' Capturing EC: up to {b(max(max(v[m]) for m in cap))}; fat-free EC: up to {b(max(max(v[m]) for m in free))} '
                '(no lambda object, only the Integer box' + (' and the returned Optional' if any('Optional' in m for m in free) else '') + ').')
    foot = ('Black bars: EC 13.0.0 ImmutableList inherits these *With methods from AbstractRichIterable, which wraps the '
            'call in Predicates.bind, so they allocate like the capturing versions.') if any(classify(cls, m)[0] == 'bound' for m in ms) else None
    emit('ea-off-bytes', f'{op} {src}: garbage per call when escape analysis is off',
         sub, 'bytes allocated per call (-XX:-DoEscapeAnalysis)', v, {m: [b(x) for x in v[m]] for m in ms},
         'Bytes per call with -XX:-DoEscapeAnalysis: the upper bound for lambda garbage.', foot)

    # 5. compact headers
    v = {m: [off[(m, t)]['bytes'] - on[(m, t)]['bytes'] for t in tests] for m in ms}
    lab = {m: [b(max(x, 0)) + (f'\n({x / off[(m, t)]["bytes"] * 100:.0f}%)' if off[(m, t)]['bytes'] > 1 else '')
               for x, t in zip(v[m], tests)] for m in ms}
    emit('coh-bytes', f'{op} {src}: bytes per call saved by compact object headers',
         f'Higher means compact headers helped more. They trim the JDK stream by {rng(v[jdk])} '
         f'per call; EC had nothing to trim. Not allocating at all saves the whole {b(max(on[(jdk, t)]["bytes"] for t in tests))}.',
         'bytes saved per call (headers off minus on)', {m: [max(x, 0) for x in v[m]] for m in ms}, lab,
         'Bytes per call saved by -XX:+UseCompactObjectHeaders (off minus on).')

    # 6. spike headroom
    v = {m: [on[(m, t)]['bytes'] * 10 for t in tests] for m in ms}
    emit('spike-headroom', f'{op} {src}: heap needed to absorb a 10-second spike',
         f'Lower is better. Derived: bytes per call x 1 million calls/s x 10 s. The JDK stream needs up to '
         f'{max(v[jdk]):,.0f} MB of young generation (or that many MB of extra collections); EC needs {max(max(v[m]) for m in ec):,.0f} MB.',
         'MB allocated in 10 s at 1 million calls/s', v, {m: [f'{x:,.0f} MB' for x in v[m]] for m in ms},
         'Young-generation memory a 10 s spike at 1 million calls/s allocates (derived).')
    return out
