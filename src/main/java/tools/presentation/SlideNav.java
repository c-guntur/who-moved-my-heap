package tools.presentation;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Keeps the slide files of one slide folder (default assets/presentation-40min) linked and assembled.
 *
 * Slide files are named <series>_<deck>_<slide>.adoc, e.g. 03_Definitions_01_02.adoc (deck 01, slide 02).
 * For every series this program:
 *   * rewrites the navigation block at the end of each slide file (everything after NAV_MARKER):
 *     Previous / Index / Next across all decks of the series, in file-name order, plus the slide number;
 *   * writes the deck file <series>_<deck>.adoc, which includes the deck's slides in order
 *     (used for the reveal.js and PDF builds; the :deck: attribute hides the per-slide header and links).
 * The slide sources are only read: with a third argument (target/slides/src in the build) the folder is copied there
 * first and everything is written into the copy, so nothing in assets/presentation-40min is ever changed or deleted.
 * The index is <series>_00_02.adoc (the agenda), or the first slide when there is no 00_02. When one of the opening
 * pages has the attribute line :talk-index: (an index of the whole talk, e.g. 00_Index_03.adoc), every Index link
 * points to that page instead, the opening pages' links included.
 * The series follow each other in file-name order: the last slide of a series links Next to the first slide of the
 * next series (the last slide of the last series has no Next link), and the first slide links Previous to the last slide
 * of the series before it.
 * Slide numbers run through the whole talk: the opening pages first (cover = 1), then every slide in file-name order.
 * The number is a [.slide-no] paragraph outside ifndef::deck, so the plain HTML, the reveal.js slides and the PDF
 * all show it (docinfo.html and docinfo-revealjs.html place it). It is recomputed on every run, so slides can still
 * be rearranged or renamed by hand.
 * The opening pages (the cover index.adoc, then 00_Index_01.adoc, 00_Index_02.adoc, ...; not part of a series)
 * get a navigation block too: they link to each other in order, the last one's Next goes to the first slide of the
 * first series, and the first slide of the first series links back to the last opening page.
 *
 * No dependencies, so it runs straight from source.
 * Usage (Java 25, from the project root): java src/main/java/tools/presentation/SlideNav.java . [slide folder] [work copy folder]
 * The slide folder is relative to the project root (or absolute); without it, assets/presentation-40min.
 * The slides profile in pom.xml runs it before converting the slides (folder: -Dslides.dir, default assets/presentation-40min).
 * Run it after adding, removing or renumbering slide files.
 */
public class SlideNav
{
    private static final String NAV_MARKER =
            "// navigation: generated by src/main/java/tools/presentation/SlideNav.java, do not edit below";
    // Markers written by earlier versions (nav.py, then SlideNav.java under assets/tools); replaced on the next run
    private static final String[] OLD_NAV_MARKERS = {
            "// navigation: generated by assets/tools/presentation/nav.py, do not edit below",
            "// navigation: generated by assets/tools/presentation/SlideNav.java, do not edit below"};
    private static final Pattern SLIDE = Pattern.compile("^(?<series>.+)_(?<deck>\\d\\d)_(?<slide>\\d\\d)\\.adoc$");
    private static final String COVER = "index.adoc";
    private static final Pattern OPENING = Pattern.compile("^(index|00_Index_\\d\\d)\\.adoc$");
    private static final Pattern DESCRIPTION = Pattern.compile("^:description: (.*)$", Pattern.MULTILINE);
    // A slide with this attribute line is hidden: no navigation links, no number, not in the deck files (and so not in the PDF)
    static final Pattern HIDDEN = Pattern.compile("^:slide-hidden:\\s*$", Pattern.MULTILINE);
    private static final Pattern TALK_INDEX = Pattern.compile("^:talk-index:\\s*$", Pattern.MULTILINE);

    public static void main(String[] args) throws IOException
    {
        // The slide sources are only read. Everything this program writes (navigation, numbers, deck files) goes into a
        // work copy of the folder (third argument, target/slides/src in the build; without it the sources themselves)
        Path sources = slidesFolder(args);
        Path folder = args.length > 2 ? workCopy(sources, Path.of(args[2]).toAbsolutePath().normalize()) : sources;
        Path decksFolder = folder;
        String slidesFromDecks = "";
        List<String> names = new ArrayList<>();
        List<String> opening = new ArrayList<>();
        try (var files = Files.list(folder))
        {
            files.forEach(file ->
            {
                String name = file.getFileName().toString();
                // Only slide and opening files are read (the folder can hold others, e.g. .DS_Store)
                boolean slide = SLIDE.matcher(name).matches();
                if (!(slide || OPENING.matcher(name).matches()) || !Files.isRegularFile(file) || isHidden(file))
                {
                    return;
                }
                if (slide)
                {
                    names.add(name);
                }
                else
                {
                    opening.add(name);
                }
            });
        }
        names.sort(null);
        opening.sort(null);
        if (opening.remove(COVER))
        {
            opening.addFirst(COVER); // the cover is index.adoc, which sorts after 00_Index_NN
        }
        boolean hasCover = opening.contains(COVER);
        String talkIndex = null;
        for (String name : opening)
        {
            String text = Files.readString(folder.resolve(name), StandardCharsets.UTF_8);
            if (talkIndex == null && TALK_INDEX.matcher(text).find())
            {
                talkIndex = name;
            }
        }

        // Slide numbers across the talk: the opening pages (only when there is a cover), then the slides in order
        List<String> talkOrder = new ArrayList<>(hasCover ? opening : List.of());
        talkOrder.addAll(names);

        List<String> allSeries = new ArrayList<>(distinct(names, "series"));
        for (int s = 0; s < allSeries.size(); s++)
        {
            String series = allSeries.get(s);
            List<String> ordered = matching(names, "series", series);
            String before = s > 0 ? matching(names, "series", allSeries.get(s - 1)).getLast()
                    : hasCover ? opening.getLast() : null;
            String after = s + 1 < allSeries.size() ? matching(names, "series", allSeries.get(s + 1)).getFirst() : null;
            LinkedHashSet<String> decks = distinct(ordered, "deck");
            String index = talkIndex != null ? talkIndex
                    : ordered.contains(series + "_00_02.adoc") ? series + "_00_02.adoc" : ordered.getFirst();

            for (int i = 0; i < ordered.size(); i++)
            {
                String name = ordered.get(i);
                Path path = folder.resolve(name);
                String text = Files.readString(path, StandardCharsets.UTF_8);
                String body = stripTrailingNewlines(beforeMarker(text)) + "\n\n";
                String previous = i > 0 ? ordered.get(i - 1) : before;
                String nav = navBlock(previous, index,
                        i + 1 < ordered.size() ? ordered.get(i + 1) : after, talkOrder.indexOf(name) + 1);
                writeIfChanged(path, body + nav);
            }

            for (String deck : decks)
            {
                List<String> slides = matching(ordered, "deck", deck);
                String first = Files.readString(folder.resolve(slides.getFirst()), StandardCharsets.UTF_8);
                Matcher description = DESCRIPTION.matcher(first);
                String content = deckFile(series, deck, slides, description.find() ? description.group(1) : "", slidesFromDecks);
                writeIfChanged(decksFolder.resolve(series + "_" + deck + ".adoc"), content);
            }
            System.out.println(series + ": " + decks.size() + " decks, " + ordered.size() + " slides, index " + index
                    + ", numbers " + (talkOrder.indexOf(ordered.getFirst()) + 1) + " to " + (talkOrder.indexOf(ordered.getLast()) + 1));
        }

        if (hasCover && !names.isEmpty())
        {
            for (int i = 0; i < opening.size(); i++)
            {
                Path path = folder.resolve(opening.get(i));
                String body = stripTrailingNewlines(beforeMarker(Files.readString(path, StandardCharsets.UTF_8))) + "\n\n";
                String next = i + 1 < opening.size() ? opening.get(i + 1) : names.getFirst();
                writeIfChanged(path, body + navBlock(i > 0 ? opening.get(i - 1) : null,
                        talkIndex != null ? talkIndex : COVER, next, i + 1));
            }
            System.out.println("opening: " + opening + ", next " + names.getFirst()
                    + (talkIndex != null ? ", talk index " + talkIndex : ""));
        }
    }

    // A fresh copy of the slide folder (files and the demo folder), so the sources stay untouched
    private static Path workCopy(Path sources, Path work) throws IOException
    {
        if (work.startsWith(sources) || sources.startsWith(work))
        {
            throw new IllegalArgumentException("The work folder " + work + " must be apart from the slide sources " + sources);
        }
        if (Files.exists(work))
        {
            try (var walk = Files.walk(work))
            {
                for (Path path : walk.sorted(java.util.Comparator.reverseOrder()).toList())
                {
                    Files.delete(path);
                }
            }
        }
        try (var walk = Files.walk(sources))
        {
            for (Path path : walk.toList())
            {
                Path target = work.resolve(sources.relativize(path).toString());
                if (Files.isDirectory(path))
                {
                    Files.createDirectories(target);
                }
                else
                {
                    Files.copy(path, target);
                }
            }
        }
        return work;
    }

    static boolean isHidden(Path file)
    {
        try
        {
            return HIDDEN.matcher(Files.readString(file, StandardCharsets.UTF_8)).find();
        }
        catch (IOException e)
        {
            throw new UncheckedIOException(e);
        }
    }

    // The slide folder: the second argument (relative to the project root, or absolute), default assets/presentation-40min
    static Path slidesFolder(String[] args)
    {
        Path root = Path.of(args.length > 0 ? args[0] : ".");
        return args.length > 1 ? root.resolve(args[1]) : root.resolve(Path.of("assets", "presentation-40min"));
    }

    // The values of one name part (series or deck), in file-name order, without repeats
    private static LinkedHashSet<String> distinct(List<String> names, String group)
    {
        LinkedHashSet<String> values = new LinkedHashSet<>();
        for (String name : names)
        {
            values.add(part(name, group));
        }
        return values;
    }

    // The names whose series or deck part equals value, in file-name order
    private static List<String> matching(List<String> names, String group, String value)
    {
        List<String> result = new ArrayList<>();
        for (String name : names)
        {
            if (part(name, group).equals(value))
            {
                result.add(name);
            }
        }
        return result;
    }

    private static String part(String name, String group)
    {
        Matcher matcher = SLIDE.matcher(name);
        matcher.matches();
        return matcher.group(group);
    }

    // The slide text before the navigation block (new or old marker, whichever comes first)
    private static String beforeMarker(String text)
    {
        int end = text.length();
        List<String> markers = new ArrayList<>(List.of(OLD_NAV_MARKERS));
        markers.add(NAV_MARKER);
        for (String marker : markers)
        {
            int at = text.indexOf(marker);
            if (at >= 0 && at < end)
            {
                end = at;
            }
        }
        return text.substring(0, end);
    }

    private static String stripTrailingNewlines(String text)
    {
        int end = text.length();
        while (end > 0 && text.charAt(end - 1) == '\n')
        {
            end--;
        }
        return text.substring(0, end);
    }

    private static String navBlock(String previous, String index, String next, int number)
    {
        String previousLink = previous != null ? "xref:" + previous + "[‹ Previous]" : "‹ Previous";
        // The last slide of the talk has no Next link
        String nextLink = next != null ? " {nbsp}|{nbsp} xref:" + next + "[Next ›]" : "";
        return NAV_MARKER + "\n"
                + "[.slide-no]\n"
                + number + "\n\n"
                + "ifndef::deck[]\n"
                + "[.deck-nav]\n"
                + previousLink + " {nbsp}|{nbsp} xref:" + index + "[⌂ Index]" + nextLink + "\n"
                + "endif::[]\n";
    }

    private static String deckFile(String series, String deck, List<String> slides, String description, String prefix)
    {
        List<String> lines = new ArrayList<>(List.of(
                "// Deck " + deck + " of " + series + ": assembled from its slide files by src/main/java/tools/presentation/SlideNav.java.",
                "// Edit the slide files, not this file. Used for the reveal.js slides and the PDF.",
                ":deck-number: " + deck,
                ":deck:"));
        if (!description.isEmpty())
        {
            lines.add(":description: " + description);
        }
        lines.add("include::" + prefix + "_deck-settings.adoc[]");
        lines.add("");
        for (String slide : slides)
        {
            lines.add("include::" + prefix + slide + "[]\n");
        }
        return String.join("\n", lines);
    }

    private static void writeIfChanged(Path path, String content) throws IOException
    {
        if (!Files.exists(path) || !Files.readString(path, StandardCharsets.UTF_8).equals(content))
        {
            Files.writeString(path, content, StandardCharsets.UTF_8);
        }
    }
}
