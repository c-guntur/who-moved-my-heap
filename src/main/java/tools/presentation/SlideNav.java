package tools.presentation;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Keeps the slide files in assets/presentation linked and assembled.
 *
 * Slide files are named <series>_<deck>_<slide>.adoc, e.g. 03_Definitions_01_02.adoc (deck 01, slide 02).
 * For every series this program:
 *   * rewrites the navigation block at the end of each slide file (everything after NAV_MARKER):
 *     Previous / Index / Next across all decks of the series, in file-name order, plus "deck slide/total";
 *   * rewrites the deck file <series>_<deck>.adoc, which includes the deck's slides in order
 *     (used for the reveal.js and PDF builds; the :deck: attribute hides the per-slide header and links).
 * The index is <series>_00_02.adoc (the agenda), or the first slide when there is no 00_02.
 *
 * No dependencies, so it runs straight from source.
 * Usage (Java 25, from the project root): java src/main/java/tools/presentation/SlideNav.java .
 * The slides profile in pom.xml runs it before converting the slides.
 * Run it after adding, removing or renumbering slide files.
 */
public class SlideNav
{
    private static final String NAV_MARKER =
            "// navigation: generated by src/main/java/tools/presentation/SlideNav.java, do not edit below";
    // Markers written by earlier versions (nav.py, then SlideNav.java under assets/tools); replaced on the next run
    private static final String[] OLD_NAV_MARKERS = {
            "// navigation: generated by assets/tools/presentation/nav.py, do not edit below",
            "// navigation: generated by assets/tools/presentation/SlideNav.java, do not edit below"};
    private static final Pattern SLIDE = Pattern.compile("^(?<series>.+)_(?<deck>\\d\\d)_(?<slide>\\d\\d)\\.adoc$");
    private static final Pattern DESCRIPTION = Pattern.compile("^:description: (.*)$", Pattern.MULTILINE);

    public static void main(String[] args) throws IOException
    {
        Path folder = Path.of(args[0], "assets", "presentation");
        List<String> names = new ArrayList<>();
        try (var files = Files.list(folder))
        {
            files.forEach(file ->
            {
                String name = file.getFileName().toString();
                if (SLIDE.matcher(name).matches())
                {
                    names.add(name);
                }
            });
        }
        names.sort(null);

        for (String series : distinct(names, "series"))
        {
            List<String> ordered = matching(names, "series", series);
            LinkedHashSet<String> decks = distinct(ordered, "deck");
            String index = ordered.contains(series + "_00_02.adoc") ? series + "_00_02.adoc" : ordered.getFirst();

            for (int i = 0; i < ordered.size(); i++)
            {
                String name = ordered.get(i);
                String deck = part(name, "deck");
                List<String> deckSlides = matching(ordered, "deck", deck);
                String position = deck + " · " + (deckSlides.indexOf(name) + 1) + "/" + deckSlides.size();
                Path path = folder.resolve(name);
                String text = Files.readString(path, StandardCharsets.UTF_8);
                String body = stripTrailingNewlines(beforeMarker(text)) + "\n\n";
                String nav = navBlock(i > 0 ? ordered.get(i - 1) : null, index,
                        i + 1 < ordered.size() ? ordered.get(i + 1) : null, position);
                writeIfChanged(path, body + nav);
            }

            for (String deck : decks)
            {
                List<String> slides = matching(ordered, "deck", deck);
                String first = Files.readString(folder.resolve(slides.getFirst()), StandardCharsets.UTF_8);
                Matcher description = DESCRIPTION.matcher(first);
                String content = deckFile(series, deck, slides, description.find() ? description.group(1) : "");
                writeIfChanged(folder.resolve(series + "_" + deck + ".adoc"), content);
            }
            System.out.println(series + ": " + decks.size() + " decks, " + ordered.size() + " slides, index " + index);
        }
    }

    // The values of one name part (series or deck), in file-name order, without repeats
    private static LinkedHashSet<String> distinct(List<String> names, String group)
    {
        LinkedHashSet<String> values = new LinkedHashSet<>();
        for (String name : names)
        {
            values.add(part(name, group));
        }
        return values;
    }

    // The names whose series or deck part equals value, in file-name order
    private static List<String> matching(List<String> names, String group, String value)
    {
        List<String> result = new ArrayList<>();
        for (String name : names)
        {
            if (part(name, group).equals(value))
            {
                result.add(name);
            }
        }
        return result;
    }

    private static String part(String name, String group)
    {
        Matcher matcher = SLIDE.matcher(name);
        matcher.matches();
        return matcher.group(group);
    }

    // The slide text before the navigation block (new or old marker, whichever comes first)
    private static String beforeMarker(String text)
    {
        int end = text.length();
        List<String> markers = new ArrayList<>(List.of(OLD_NAV_MARKERS));
        markers.add(NAV_MARKER);
        for (String marker : markers)
        {
            int at = text.indexOf(marker);
            if (at >= 0 && at < end)
            {
                end = at;
            }
        }
        return text.substring(0, end);
    }

    private static String stripTrailingNewlines(String text)
    {
        int end = text.length();
        while (end > 0 && text.charAt(end - 1) == '\n')
        {
            end--;
        }
        return text.substring(0, end);
    }

    private static String navBlock(String previous, String index, String next, String position)
    {
        String previousLink = previous != null ? "xref:" + previous + "[‹ Previous]" : "‹ Previous";
        String nextLink = next != null ? "xref:" + next + "[Next ›]" : "xref:" + index + "[Next: index ›]";
        return NAV_MARKER + "\n"
                + "ifndef::deck[]\n"
                + "[.deck-nav]\n"
                + previousLink + " {nbsp}|{nbsp} xref:" + index + "[⌂ Index] {nbsp}|{nbsp} " + nextLink
                + " {nbsp}{nbsp} [.deck-pos]#" + position + "#\n"
                + "endif::[]\n";
    }

    private static String deckFile(String series, String deck, List<String> slides, String description)
    {
        List<String> lines = new ArrayList<>(List.of(
                "// Deck " + deck + " of " + series + ": assembled from its slide files by src/main/java/tools/presentation/SlideNav.java.",
                "// Edit the slide files, not this file. Used for the reveal.js slides and the PDF.",
                ":deck-number: " + deck,
                ":deck:"));
        if (!description.isEmpty())
        {
            lines.add(":description: " + description);
        }
        lines.add("include::_deck-settings.adoc[]");
        lines.add("");
        for (String slide : slides)
        {
            lines.add("include::" + slide + "[]\n");
        }
        return String.join("\n", lines);
    }

    private static void writeIfChanged(Path path, String content) throws IOException
    {
        if (!Files.exists(path) || !Files.readString(path, StandardCharsets.UTF_8).equals(content))
        {
            Files.writeString(path, content, StandardCharsets.UTF_8);
        }
    }
}
